import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { mkdtemp, rm } from "node:fs/promises";
import { createRequire } from "node:module";
import { join } from "node:path";
import { test } from "node:test";
import { fileURLToPath } from "node:url";
import express from "express";
import { build } from "esbuild";
import { drizzle } from "drizzle-orm/node-postgres";

const testDir = fileURLToPath(new URL(".", import.meta.url));
const requireDb = createRequire(new URL("../../../lib/db/package.json", import.meta.url));
const { Pool } = requireDb("pg");

async function request(server, userId, path, options = {}) {
  const { port } = server.address();
  const response = await fetch(`http://127.0.0.1:${port}${path}`, {
    ...options,
    headers: { "x-test-user-id": userId, ...options.headers },
  });
  const raw = await response.text();
  return { status: response.status, body: JSON.parse(raw), raw };
}

test("POST bukti menyimpan caseId dari URL di PostgreSQL tanpa mengubah bukti pemilik lain", async () => {
  assert.ok(process.env.DATABASE_URL, "DATABASE_URL diperlukan untuk pengujian integrasi PostgreSQL");
  assert.notEqual(process.env.NODE_ENV, "production", "Pengujian tidak boleh dijalankan dalam mode produksi");

  const schema = `sbu_evidence_test_${randomUUID().replaceAll("-", "")}`;
  const admin = new Pool({ connectionString: process.env.DATABASE_URL, max: 1 });
  const isolated = new Pool({
    connectionString: process.env.DATABASE_URL,
    options: `-c search_path=${schema}`,
    max: 2,
  });
  const temporaryDir = await mkdtemp(join(testDir, ".sbu-evidence-pg-"));
  let created = false;
  let server;

  try {
    await admin.query(`CREATE SCHEMA "${schema}"`);
    created = true;
    for (const table of ["sbu_profiles", "sbu_cases", "sbu_evidence"]) {
      await admin.query(`CREATE TABLE "${schema}".${table} (LIKE public.${table} INCLUDING ALL)`);
    }
    // Serial defaults copied by LIKE can refer to public sequences; replace them
    // so inserts into cloned tables cannot advance production/application sequences.
    for (const table of ["sbu_cases", "sbu_evidence"]) {
      await admin.query(`ALTER TABLE "${schema}".${table} ALTER COLUMN id DROP DEFAULT`);
      await admin.query(`ALTER TABLE "${schema}".${table} ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY`);
    }

    const { rows: [target] } = await isolated.query(`
      SELECT current_schema() AS current_schema,
             (SELECT n.nspname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
              WHERE c.oid = to_regclass('sbu_profiles')) AS profiles_schema,
             (SELECT n.nspname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
              WHERE c.oid = to_regclass('sbu_cases')) AS cases_schema,
             (SELECT n.nspname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
              WHERE c.oid = to_regclass('sbu_evidence')) AS evidence_schema
    `);
    assert.deepEqual(target, {
      current_schema: schema, profiles_schema: schema, cases_schema: schema, evidence_schema: schema,
    }, "Koneksi route harus memakai seluruh tabel klon, bukan tabel aplikasi");

    const owner = `test-owner-${randomUUID()}`;
    const otherOwner = `test-other-${randomUUID()}`;
    await isolated.query(
      "INSERT INTO sbu_profiles (user_id) VALUES ($1), ($2)", [owner, otherOwner],
    );
    const { rows: [source] } = await isolated.query(
      `INSERT INTO sbu_cases (owner_id, company_name, request_type, qualification, classification)
       VALUES ($1, 'Pemohon A', 'baru', 'kecil', 'konstruksi') RETURNING id`, [owner],
    );
    const { rows: [other] } = await isolated.query(
      `INSERT INTO sbu_cases (owner_id, company_name, request_type, qualification, classification)
       VALUES ($1, 'Pemohon B', 'baru', 'kecil', 'konstruksi') RETURNING id`, [otherOwner],
    );
    const { rows: [existing] } = await isolated.query(
      `INSERT INTO sbu_evidence (case_id, code, title, note)
       VALUES ($1, 'legalitas', 'Bukti pemilik lain', 'Tetap privat')
       RETURNING id, case_id, code, title, note, updated_at`, [other.id],
    );
    const readEvidence = async () => (await isolated.query(
      "SELECT id, case_id, code, title, note, updated_at FROM sbu_evidence ORDER BY id",
    )).rows;

    globalThis.__evidenceTestDb = drizzle(isolated);
    await build({
      entryPoints: [join(testDir, "../src/routes/sbu.ts")],
      outfile: join(temporaryDir, "route.mjs"),
      bundle: true,
      platform: "node",
      format: "esm",
      external: ["express"],
      plugins: [{
        name: "isolated-evidence-db",
        setup(builder) {
          builder.onResolve({ filter: /^@workspace\/db$/ }, () => ({ path: "db", namespace: "evidence-test" }));
          builder.onResolve({ filter: /^@clerk\/express$/ }, () => ({ path: "auth", namespace: "evidence-test" }));
          builder.onResolve({ filter: /^@workspace\/api-zod$/ }, () => ({
            path: join(testDir, "../../../lib/api-zod/src/index.ts"),
          }));
          builder.onLoad({ filter: /.*/, namespace: "evidence-test" }, (args) => ({
            contents: args.path === "auth"
              ? `export const getAuth = (req) => ({ userId: req.get("x-test-user-id") });`
               : `export { profilesTable, casesTable, evidenceTable, transitionVerificationsTable } from ${
                JSON.stringify(join(testDir, "../../../lib/db/src/schema/sbu.ts"))
              }; export const db = globalThis.__evidenceTestDb;`,
            loader: "js",
            resolveDir: testDir,
          }));
        },
      }],
    });

    const { default: router } = await import(join(temporaryDir, "route.mjs"));
    const app = express();
    app.use(express.json());
    app.use("/api", router);
    server = app.listen(0);

    const posted = await request(server, owner, `/api/cases/${source.id}/evidence`, {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify({
        caseId: other.id, code: "pajak", title: "Bukti pemohon A", note: "Hanya milik A",
      }),
    });
    assert.equal(posted.status, 201, posted.raw);
    assert.equal(posted.body.caseId, source.id, "respons harus mengikuti ID URL");

    const rows = await readEvidence();
    assert.equal(rows.length, 2, "hanya satu bukti baru boleh tersimpan");
    assert.deepEqual(rows.filter((row) => row.case_id === other.id), [existing],
      "baris milik pengguna lain tidak boleh bertambah atau berubah");
    assert.deepEqual(rows.filter((row) => row.case_id === source.id).map(
      ({ id, case_id, code, title, note }) => ({ id, case_id, code, title, note }),
    ), [{
      id: posted.body.id, case_id: source.id, code: "pajak",
      title: "Bukti pemohon A", note: "Hanya milik A",
    }]);

    const ownList = await request(server, owner, `/api/cases/${source.id}/evidence`);
    const otherList = await request(server, otherOwner, `/api/cases/${other.id}/evidence`);
    assert.equal(ownList.status, 200, ownList.raw);
    assert.equal(otherList.status, 200, otherList.raw);
    assert.deepEqual(ownList.body.map(({ id }) => id), [posted.body.id]);
    assert.deepEqual(otherList.body.map(({ id }) => id), [existing.id]);
  } finally {
    if (server) await new Promise((resolve, reject) => server.close((error) => error ? reject(error) : resolve()));
    delete globalThis.__evidenceTestDb;
    try {
      try {
        await isolated.end();
      } finally {
        if (created) await admin.query(`DROP SCHEMA "${schema}" CASCADE`);
      }
    } finally {
      await admin.end();
      await rm(temporaryDir, { recursive: true, force: true });
    }
  }
});