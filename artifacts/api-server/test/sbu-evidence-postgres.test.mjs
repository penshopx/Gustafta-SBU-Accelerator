import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { mkdtemp, rm } from "node:fs/promises";
import { createRequire } from "node:module";
import { join } from "node:path";
import { test } from "node:test";
import { fileURLToPath } from "node:url";
import express from "express";
import { build } from "esbuild";
import { drizzle } from "drizzle-orm/node-postgres";
import { createRestrictedRoutePool } from "./helpers/restricted-postgres.mjs";

const testDir = fileURLToPath(new URL(".", import.meta.url));
const requireDb = createRequire(new URL("../../../lib/db/package.json", import.meta.url));
const { Pool } = requireDb("pg");

async function request(server, userId, path, options = {}) {
  const { port } = server.address();
  const response = await fetch(`http://127.0.0.1:${port}${path}`, {
    ...options,
    headers: { "x-test-user-id": userId, "X-SBU-Form-Owner": userId, ...options.headers },
  });
  const raw = await response.text();
  return { status: response.status, body: JSON.parse(raw), raw };
}

test("Rute bukti menjaga kepemilikan, keunikan kategori, dan urutan di PostgreSQL", async (t) => {
  assert.ok(process.env.DATABASE_URL, "DATABASE_URL diperlukan untuk pengujian integrasi PostgreSQL");
  assert.notEqual(process.env.NODE_ENV, "production", "Pengujian tidak boleh dijalankan dalam mode produksi");

  const schema = `sbu_evidence_test_${randomUUID().replaceAll("-", "")}`;
  const admin = new Pool({ connectionString: process.env.DATABASE_URL, max: 1 });
  let isolated;
  let restricted;
  const temporaryDir = await mkdtemp(join(testDir, ".sbu-evidence-pg-"));
  let created = false;
  let server;

  try {
    const { rows: indexes } = await admin.query(`
      SELECT i.indisunique, i.indisvalid,
             i.indpred IS NULL AS unfiltered,
             i.indexprs IS NULL AS plain_columns,
             ARRAY(
               SELECT a.attname
               FROM unnest(i.indkey) WITH ORDINALITY AS key(attnum, position)
               JOIN pg_attribute a ON a.attrelid = tbl.oid AND a.attnum = key.attnum
               WHERE key.position <= i.indnkeyatts
               ORDER BY key.position
             )::text[] AS columns
      FROM pg_index i
      JOIN pg_class idx ON idx.oid = i.indexrelid
      JOIN pg_class tbl ON tbl.oid = i.indrelid
      JOIN pg_namespace ns ON ns.oid = tbl.relnamespace
      WHERE ns.nspname = 'public'
        AND tbl.relname = 'sbu_evidence'
        AND idx.relname = 'sbu_evidence_case_code_unique'
    `);
    assert.deepEqual(indexes, [{
      indisunique: true, indisvalid: true, unfiltered: true, plain_columns: true,
      columns: ["case_id", "code"],
    }], "Indeks unik kategori bukti harus terpasang di tabel aplikasi sebelum diklon");

    await admin.query(`CREATE SCHEMA "${schema}"`);
    created = true;
    for (const table of ["sbu_profiles", "sbu_cases", "sbu_evidence"]) {
      await admin.query(`CREATE TABLE "${schema}".${table} (LIKE public.${table} INCLUDING ALL)`);
    }
    // Serial defaults copied by LIKE can refer to public sequences; replace them
    // so inserts into cloned tables cannot advance production/application sequences.
    for (const table of ["sbu_cases", "sbu_evidence"]) {
      await admin.query(`ALTER TABLE "${schema}".${table} ALTER COLUMN id DROP DEFAULT`);
      await admin.query(`ALTER TABLE "${schema}".${table} ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY`);
    }
    restricted = await createRestrictedRoutePool(admin, schema);
    isolated = restricted.pool;

    const { rows: [target] } = await isolated.query(`
      SELECT current_schema() AS current_schema,
             (SELECT n.nspname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
              WHERE c.oid = to_regclass('sbu_profiles')) AS profiles_schema,
             (SELECT n.nspname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
              WHERE c.oid = to_regclass('sbu_cases')) AS cases_schema,
             (SELECT n.nspname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
              WHERE c.oid = to_regclass('sbu_evidence')) AS evidence_schema
    `);
    assert.deepEqual(target, {
      current_schema: schema, profiles_schema: schema, cases_schema: schema, evidence_schema: schema,
    }, "Koneksi route harus memakai seluruh tabel klon, bukan tabel aplikasi");

    const owner = `test-owner-${randomUUID()}`;
    const otherOwner = `test-other-${randomUUID()}`;
    await isolated.query(
      "INSERT INTO sbu_profiles (user_id) VALUES ($1), ($2)", [owner, otherOwner],
    );
    const { rows: [source] } = await isolated.query(
      `INSERT INTO sbu_cases (owner_id, company_name, request_type, qualification, classification)
       VALUES ($1, 'Pemohon A', 'baru', 'kecil', 'konstruksi') RETURNING id`, [owner],
    );
    const { rows: [other] } = await isolated.query(
      `INSERT INTO sbu_cases (owner_id, company_name, request_type, qualification, classification)
       VALUES ($1, 'Pemohon B', 'baru', 'kecil', 'konstruksi') RETURNING id`, [otherOwner],
    );
    const { rows: [existing] } = await isolated.query(
      `INSERT INTO sbu_evidence (case_id, code, title, note)
       VALUES ($1, 'legalitas', 'Bukti pemilik lain', 'Tetap privat')
       RETURNING id, case_id, code, title, note, updated_at`, [other.id],
    );
    const readEvidence = async () => (await isolated.query(
      "SELECT id, case_id, code, title, note, updated_at FROM sbu_evidence ORDER BY id",
    )).rows;

    globalThis.__evidenceTestDb = drizzle(isolated);
    await build({
      entryPoints: [join(testDir, "../src/routes/sbu.ts")],
      outfile: join(temporaryDir, "route.mjs"),
      bundle: true,
      platform: "node",
      format: "esm",
      external: ["express"],
      plugins: [{
        name: "isolated-evidence-db",
        setup(builder) {
          builder.onResolve({ filter: /^@workspace\/db$/ }, () => ({ path: "db", namespace: "evidence-test" }));
          builder.onResolve({ filter: /^@clerk\/express$/ }, () => ({ path: "auth", namespace: "evidence-test" }));
          builder.onResolve({ filter: /^@workspace\/api-zod$/ }, () => ({
            path: join(testDir, "../../../lib/api-zod/src/index.ts"),
          }));
          builder.onLoad({ filter: /.*/, namespace: "evidence-test" }, (args) => ({
            contents: args.path === "auth"
              ? `export const getAuth = (req) => ({ userId: req.get("x-test-user-id") });`
               : `export { profilesTable, casesTable, evidenceTable, transitionVerificationsTable } from ${
                JSON.stringify(join(testDir, "../../../lib/db/src/schema/sbu.ts"))
              }; export const db = globalThis.__evidenceTestDb;`,
            loader: "js",
            resolveDir: testDir,
          }));
        },
      }],
    });

    const { default: router } = await import(join(temporaryDir, "route.mjs"));
    const app = express();
    app.use(express.json());
    app.use("/api", router);
    server = app.listen(0);

    const beforeDeniedPost = await readEvidence();
    const denied = await request(server, owner, `/api/cases/${other.id}/evidence`, {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify({
        caseId: source.id, code: "pajak", title: "Tidak boleh masuk", note: "Milik pemohon A",
      }),
    });
    assert.equal(denied.status, 404, denied.raw);
    assert.deepEqual(await readEvidence(), beforeDeniedPost,
      "POST ke URL milik pengguna lain tidak boleh menambah atau mengubah bukti siapa pun");

    const posted = await request(server, owner, `/api/cases/${source.id}/evidence`, {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify({
        caseId: other.id, code: "pajak", title: "Bukti pemohon A", note: "Hanya milik A",
      }),
    });
    assert.equal(posted.status, 201, posted.raw);
    assert.equal(posted.body.caseId, source.id, "respons harus mengikuti ID URL");

    const rows = await readEvidence();
    assert.equal(rows.length, 2, "hanya satu bukti baru boleh tersimpan");
    assert.deepEqual(rows.filter((row) => row.case_id === other.id), [existing],
      "baris milik pengguna lain tidak boleh bertambah atau berubah");
    assert.deepEqual(rows.filter((row) => row.case_id === source.id).map(
      ({ id, case_id, code, title, note }) => ({ id, case_id, code, title, note }),
    ), [{
      id: posted.body.id, case_id: source.id, code: "pajak",
      title: "Bukti pemohon A", note: "Hanya milik A",
    }]);

    const ownList = await request(server, owner, `/api/cases/${source.id}/evidence`);
    const otherList = await request(server, otherOwner, `/api/cases/${other.id}/evidence`);
    assert.equal(ownList.status, 200, ownList.raw);
    assert.equal(otherList.status, 200, otherList.raw);
    assert.deepEqual(ownList.body.map(({ id }) => id), [posted.body.id]);
    assert.deepEqual(otherList.body.map(({ id }) => id), [existing.id]);

    const patched = await request(server, owner, `/api/cases/${source.id}/evidence/${posted.body.id}`, {
      method: "PATCH",
      headers: { "content-type": "application/json" },
      body: JSON.stringify({
        caseId: other.id, title: "Bukti pemohon A diperbarui", note: "Tetap milik A",
      }),
    });
    assert.equal(patched.status, 200, patched.raw);
    assert.deepEqual({
      id: patched.body.id, caseId: patched.body.caseId, code: patched.body.code,
      title: patched.body.title, note: patched.body.note,
    }, {
      id: posted.body.id, caseId: source.id, code: "pajak",
      title: "Bukti pemohon A diperbarui", note: "Tetap milik A",
    }, "Respons PATCH harus tetap menunjuk permohonan asal dari URL");

    const afterPatch = await readEvidence();
    assert.equal(afterPatch.length, 2, "PATCH tidak boleh membuat atau menghapus bukti");
    assert.deepEqual(afterPatch.filter((row) => row.case_id === other.id), [existing],
      "Baris permohonan tujuan tidak boleh berubah");
    assert.deepEqual(afterPatch.filter((row) => row.id === posted.body.id).map((row) => ({
      id: row.id, caseId: row.case_id, code: row.code, title: row.title,
      note: row.note, updatedAt: row.updated_at.toISOString(),
    })), [patched.body], "Baris yang tersimpan harus sesuai respons PATCH dan tetap di permohonan asal");

    const competing = [
      { code: "sertifikat", title: "Kiriman pertama", note: "Catatan pertama" },
      { code: "sertifikat", title: "Kiriman kedua", note: "Catatan kedua" },
    ];
    // Launch both HTTP requests before awaiting either one; the route uses the
    // isolated pool (max 2) so the unique index resolves the competing inserts.
    const responses = await Promise.all(competing.map((body) => request(
      server, owner, `/api/cases/${source.id}/evidence`, {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify(body),
      },
    )));
    assert.deepEqual(responses.map(({ status }) => status).sort(), [201, 409],
      `Dua kiriman kategori sama harus menghasilkan satu 201 dan satu 409: ${responses.map((r) => r.raw)}`);
    const winnerIndex = responses.findIndex(({ status }) => status === 201);
    const winner = responses[winnerIndex];
    assert.equal(winner.body.caseId, source.id);
    assert.equal(winner.body.code, "sertifikat");
    assert.match(responses[1 - winnerIndex].body.error, /Kategori bukti sudah dicatat/);

    const afterRace = await readEvidence();
    assert.deepEqual(afterRace.filter((row) => row.case_id === other.id), [existing],
      "Bukti pemohon lain tidak boleh berubah akibat kiriman bersamaan");
    assert.deepEqual(afterRace.filter((row) => row.case_id === source.id && row.code === "pajak"),
      afterPatch.filter((row) => row.case_id === source.id),
      "Kategori yang sudah ada tidak boleh berubah akibat kiriman bersamaan");
    assert.deepEqual(afterRace.filter((row) => row.case_id === source.id && row.code === "sertifikat")
      .map(({ id, case_id, code, title, note, updated_at }) => ({
        id, case_id, code, title, note, updatedAt: updated_at.toISOString(),
      })), [{
        id: winner.body.id, case_id: source.id, code: "sertifikat",
        title: competing[winnerIndex].title, note: competing[winnerIndex].note,
        updatedAt: winner.body.updatedAt,
      }],
      "Hanya kiriman pemenang yang tersimpan, tanpa tertimpa oleh kiriman yang ditolak");
    assert.equal(afterRace.length, 3, "Total hanya satu kategori baru boleh tersimpan");

    await t.test("GET bukti konsisten berdasarkan updatedAt menurun lalu ID menurun saat waktu seri", async () => {
      const { rows: [orderingCase] } = await isolated.query(
        `INSERT INTO sbu_cases (owner_id, company_name, request_type, qualification, classification)
         VALUES ($1, 'Pemohon uji urutan', 'baru', 'kecil', 'konstruksi') RETURNING id`, [owner],
      );
      const newest = "2026-06-03T10:00:00.000Z";
      const tied = "2026-06-02T10:00:00.000Z";
      const oldest = "2026-06-01T10:00:00.000Z";
      // Neither insertion order nor ID order matches the required result.
      // Explicit IDs and all writes belong solely to the restricted clone.
      const fixtures = [
        { id: 40, updatedAt: tied },
        { id: 10, updatedAt: newest },
        { id: 60, updatedAt: oldest },
        { id: 20, updatedAt: tied },
        { id: 50, updatedAt: tied },
        { id: 30, updatedAt: oldest },
      ];
      for (const fixture of fixtures) {
        await isolated.query(
          `INSERT INTO sbu_evidence (id, case_id, code, title, note, updated_at)
           VALUES ($1, $2, $3, $4, '', $5)`,
          [fixture.id, orderingCase.id, `urutan-${fixture.id}`, `Bukti ${fixture.id}`, fixture.updatedAt],
        );
      }
      const { rows: stored } = await isolated.query(
        "SELECT id, updated_at FROM sbu_evidence WHERE case_id = $1 ORDER BY id", [orderingCase.id],
      );
      assert.deepEqual(stored.map(({ id, updated_at }) => ({ id, updatedAt: updated_at.toISOString() })),
        [...fixtures].sort((a, b) => a.id - b.id),
        "PostgreSQL harus menyimpan waktu seri identik dan ID berbeda sesuai fixture");

      const expected = [
        { id: 10, updatedAt: newest },
        { id: 50, updatedAt: tied },
        { id: 40, updatedAt: tied },
        { id: 20, updatedAt: tied },
        { id: 60, updatedAt: oldest },
        { id: 30, updatedAt: oldest },
      ];
      for (let attempt = 1; attempt <= 5; attempt++) {
        const listed = await request(server, owner, `/api/cases/${orderingCase.id}/evidence`);
        assert.equal(listed.status, 200, listed.raw);
        assert.deepEqual(listed.body.map(({ id, updatedAt }) => ({ id, updatedAt })), expected,
          `GET ke-${attempt} harus mengurutkan waktu menurun dan memecahkan waktu seri dengan ID menurun`);
        assert.ok(listed.body.every(({ caseId }) => caseId === orderingCase.id),
          "Daftar hanya boleh memuat bukti dari permohonan yang diminta");
      }
    });
  } finally {
    if (server) await new Promise((resolve, reject) => server.close((error) => error ? reject(error) : resolve()));
    delete globalThis.__evidenceTestDb;
    try {
      try {
        if (restricted) await restricted.close();
      } finally {
        if (created) await admin.query(`DROP SCHEMA "${schema}" CASCADE`);
      }
    } finally {
      await admin.end();
      await rm(temporaryDir, { recursive: true, force: true });
    }
  }
});