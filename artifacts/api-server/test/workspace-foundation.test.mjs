import assert from "node:assert/strict";
import { test } from "node:test";
import { mkdtemp, readFile, rm } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { randomUUID } from "node:crypto";
import { createRequire } from "node:module";
import express from "express";
import { drizzle } from "drizzle-orm/node-postgres";
import { build } from "esbuild";

const testDir = fileURLToPath(new URL(".", import.meta.url));
const root = fileURLToPath(new URL("../../../", import.meta.url));
const { Pool } = createRequire(new URL("../../../lib/db/package.json", import.meta.url))("pg");

test("workspace migration, owner isolation and atomic audit use isolated real Postgres", {
  skip: !process.env.DATABASE_URL,
}, async () => {
  assert.notEqual(process.env.NODE_ENV, "production");
  const schema = `sbu_workspace_test_${randomUUID().replaceAll("-", "")}`;
  const temporaryDir = await mkdtemp(join(testDir, ".workspace-test-"));
  const admin = new Pool({ connectionString: process.env.DATABASE_URL });
  let isolated, server;
  const ids = { a: "workspace_fixture_owner_a", b: "workspace_fixture_owner_b" };
  try {
    await admin.query(`CREATE SCHEMA "${schema}"`);
    for (const table of ["sbu_profiles", "sbu_cases", "sbu_evidence", "sbu_transition_verifications"]) {
      await admin.query(`CREATE TABLE "${schema}".${table} (LIKE public.${table} INCLUDING ALL)`);
    }
    // LIKE copies public sequence defaults, not foreign keys. Never consume
    // public sequence IDs or mutate public user data in this test.
    for (const table of ["sbu_cases", "sbu_evidence"]) {
      await admin.query(`ALTER TABLE "${schema}".${table} ALTER COLUMN id DROP DEFAULT`);
      await admin.query(`ALTER TABLE "${schema}".${table} ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY`);
    }
    await admin.query(`ALTER TABLE "${schema}".sbu_cases DROP COLUMN client_id`);
    isolated = new Pool({
      connectionString: process.env.DATABASE_URL,
      options: `-c search_path=${schema}`,
    });
    const { rows: [location] } = await isolated.query(`
      SELECT current_schema() AS schema,
      (SELECT n.nspname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
       WHERE c.oid = to_regclass('sbu_cases')) AS cases_schema
    `);
    assert.equal(location.schema, schema);
    assert.equal(location.cases_schema, schema);
    await isolated.query(
      "INSERT INTO sbu_profiles(user_id, role) VALUES ($1, 'kontraktor'), ($2, 'konsultan')", [ids.a, ids.b],
    );
    await isolated.query(`
      INSERT INTO sbu_cases(owner_id, company_name, request_type, qualification, classification, existing_sbu_expires_on)
      VALUES ($1, 'Fixture company A', 'baru', 'kecil', 'Fixture A', '2027-01-09'),
             ($1, 'Fixture company A2', 'perpanjangan', 'menengah', 'Fixture A2', NULL),
             ($2, 'Fixture company B', 'baru', 'besar', 'Fixture B', NULL)
    `, [ids.a, ids.b]);
    const original = (await isolated.query("SELECT * FROM sbu_cases ORDER BY id")).rows;
    const sql = await readFile(join(root, "lib/db/migrations/workspace-foundation.sql"), "utf8");
    await isolated.query(sql);
    await isolated.query(sql);
    const migrated = (await isolated.query("SELECT * FROM sbu_cases ORDER BY id")).rows;
    assert.deepEqual(migrated.map(({ client_id, ...old }) => old), original);
    assert.ok(migrated.every((item) => Number.isInteger(item.client_id)));
    assert.equal(migrated[0].client_id, migrated[1].client_id);
    assert.notEqual(migrated[0].client_id, migrated[2].client_id);
    assert.equal((await isolated.query("SELECT count(*)::int AS n FROM sbu_clients")).rows[0].n, 2);

    // A controlled authentication fixture, NOT fabricated Clerk cookies or a
    // production authentication bypass. Persistence/context/route are real.
    globalThis.__workspaceFixtureDb = drizzle(isolated);
    await build({
      entryPoints: [join(testDir, "../src/routes/sbu.ts")],
      outfile: join(temporaryDir, "route.mjs"),
      bundle: true, platform: "node", format: "esm", external: ["express", "@google-cloud/*"],
      plugins: [{
        name: "workspace-fixtures",
        setup(builder) {
          builder.onResolve({ filter: /^@workspace\/db$/ }, () => ({ path: "db", namespace: "workspace-test" }));
          builder.onResolve({ filter: /^@clerk\/express$/ }, () => ({ path: "auth", namespace: "workspace-test" }));
          builder.onResolve({ filter: /^@workspace\/api-zod$/ }, () => ({
            path: join(root, "lib/api-zod/src/index.ts"),
          }));
          builder.onLoad({ filter: /.*/, namespace: "workspace-test" }, ({ path }) => ({
            resolveDir: root,
            contents: path === "auth"
              ? "export function getAuth(req) { return req.controlledTestSession ?? { userId: null }; }"
              : `export const db = globalThis.__workspaceFixtureDb;
                 export * from ${JSON.stringify(join(root, "lib/db/src/schema/index.ts"))};`,
          }));
        },
      }],
    });
    const { default: router } = await import(join(temporaryDir, "route.mjs"));
    const app = express();
    app.use(express.json());
    const sessions = { "Bearer fixture-session-a": ids.a, "Bearer fixture-session-b": ids.b };
    app.use((req, _res, next) => {
      req.controlledTestSession = { userId: sessions[req.get("Authorization")] ?? null };
      next();
    });
    app.use("/api", router);
    app.use((_error, _req, res, _next) => res.status(500).json({ error: "Fixture failure" }));
    server = await new Promise((resolve) => {
      const instance = app.listen(0, "127.0.0.1", () => resolve(instance));
    });
    const url = `http://127.0.0.1:${server.address().port}/api`;
    const headers = (account, write = false) => ({
      Authorization: `Bearer fixture-session-${account}`,
      "X-SBU-Form-Owner": ids[account],
      ...(write ? { "Content-Type": "application/json" } : {}),
    });
    assert.equal((await fetch(`${url}/workspace`)).status, 401);
    const workspaceAResponse = await fetch(`${url}/workspace`, { headers: headers("a") });
    assert.equal(workspaceAResponse.status, 200);
    assert.equal(workspaceAResponse.headers.get("cache-control"), "private, no-store");
    const workspaceA = await workspaceAResponse.json();
    const workspaceB = await (await fetch(`${url}/workspace`, { headers: headers("b") })).json();
    assert.notEqual(workspaceA.orgId, workspaceB.orgId);
    assert.ok(workspaceA.clientIds.every((id) => !workspaceB.clientIds.includes(id)));
    assert.equal(workspaceA.userId, ids.a);
    const forgedWorkspace = await (await fetch(`${url}/workspace`, {
      headers: { ...headers("a"), "X-Org-Id": String(workspaceB.orgId) },
    })).json();
    assert.equal(forgedWorkspace.orgId, workspaceA.orgId);

    const listA = await (await fetch(`${url}/cases`, { headers: headers("a") })).json();
    assert.equal(listA.length, 2);
    assert.ok(listA.every((item) => item.clientId === migrated[0].client_id));
    const foreignId = migrated[2].id;
    for (const suffix of ["", "/evidence", "/assessment", "/preparation-summary"]) {
      assert.equal((await fetch(`${url}/cases/${foreignId}${suffix}`, { headers: headers("a") })).status, 404);
    }
    for (const method of ["PATCH", "DELETE"]) {
      assert.equal((await fetch(`${url}/cases/${foreignId}`, {
        method, headers: headers("a", true),
        ...(method === "PATCH" ? { body: JSON.stringify({ companyName: "Forbidden update" }) } : {}),
      })).status, 404);
    }
    const createdResponse = await fetch(`${url}/cases`, {
      method: "POST", headers: headers("a", true),
      body: JSON.stringify({
        companyName: "Synthetic new company", requestType: "baru", qualification: "kecil",
        classification: "Synthetic", clientId: workspaceB.clientIds[0], orgId: workspaceB.orgId,
      }),
    });
    assert.equal(createdResponse.status, 201);
    const created = await createdResponse.json();
    assert.equal(created.clientId, workspaceA.clientIds[0]);
    assert.equal((await fetch(`${url}/cases/${created.id}`, {
      method: "PATCH", headers: { ...headers("a", true), "X-SBU-Form-Owner": ids.b },
      body: JSON.stringify({ status: "ditinjau" }),
    })).status, 409);
    const updated = await fetch(`${url}/cases/${created.id}`, {
      method: "PATCH", headers: headers("a", true), body: JSON.stringify({ status: "ditinjau" }),
    });
    assert.equal(updated.status, 200);
    const audit = (await isolated.query("SELECT * FROM sbu_audit_logs ORDER BY id")).rows;
    assert.deepEqual(audit.map((item) => item.action), ["case.created", "case.updated"]);
    assert.ok(audit.every((item) => item.org_id === workspaceA.orgId && item.user_id === ids.a));
    assert.ok(!JSON.stringify(audit).includes("Synthetic new company"), "audit must not copy company/evidence content");
    // Fail audit storage deliberately. Case updates must roll back as a unit.
    await isolated.query(`
      CREATE FUNCTION reject_fixture_audit() RETURNS trigger LANGUAGE plpgsql AS $$
        BEGIN RAISE EXCEPTION 'fixture audit rejected'; END;
      $$;
      CREATE TRIGGER reject_fixture_audit BEFORE INSERT ON sbu_audit_logs
      FOR EACH ROW EXECUTE FUNCTION reject_fixture_audit();
    `);
    assert.equal((await fetch(`${url}/cases/${created.id}`, {
      method: "PATCH", headers: headers("a", true), body: JSON.stringify({ status: "selesai_persiapan" }),
    })).status, 500);
    assert.equal((await isolated.query("SELECT status FROM sbu_cases WHERE id = $1", [created.id])).rows[0].status, "ditinjau");
    await isolated.query("DROP TRIGGER reject_fixture_audit ON sbu_audit_logs");
    assert.equal((await fetch(`${url}/cases/${created.id}`, {
      method: "DELETE", headers: headers("a", true),
    })).status, 204);
    assert.equal((await isolated.query("SELECT action FROM sbu_audit_logs ORDER BY id DESC LIMIT 1")).rows[0].action, "case.deleted");
    assert.deepEqual((await isolated.query("SELECT * FROM sbu_cases WHERE owner_id = $1", [ids.b])).rows, [migrated[2]]);
  } finally {
    if (server) await new Promise((resolve) => server.close(resolve));
    delete globalThis.__workspaceFixtureDb;
    if (isolated) await isolated.end();
    await admin.query(`DROP SCHEMA IF EXISTS "${schema}" CASCADE`);
    await admin.end();
    await rm(temporaryDir, { recursive: true, force: true });
  }
});
