import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { mkdtemp, rm } from "node:fs/promises";
import { createRequire } from "node:module";
import { join } from "node:path";
import { test } from "node:test";
import { fileURLToPath } from "node:url";
import express from "express";
import { drizzle } from "drizzle-orm/node-postgres";
import { createRestrictedRoutePool } from "./helpers/restricted-postgres.mjs";
import { buildCaseRouteFixture, caseRoutePreflight } from "./helpers/sbu-case-route-fixture.mjs";

const testDir = fileURLToPath(new URL(".", import.meta.url));
const requireDb = createRequire(new URL("../../../lib/db/package.json", import.meta.url));
const { Pool } = requireDb("pg");
const preflight = caseRoutePreflight("__caseTestDb");

test("fixture permohonan memuat seluruh rute tanpa PostgreSQL", preflight);

async function request(server, userId, path, options = {}) {
  const { port } = server.address();
  const response = await fetch(`http://127.0.0.1:${port}${path}`, {
    ...options,
    headers: { "x-test-user-id": userId, "X-SBU-Form-Owner": userId, ...options.headers },
  });
  const raw = await response.text();
  return { status: response.status, body: JSON.parse(raw), raw };
}

test("PATCH permohonan di PostgreSQL mempertahankan kolom lain dan tidak memindahkan pemilik", async (t) => {
  await preflight();
  assert.ok(process.env.DATABASE_URL, "DATABASE_URL diperlukan untuk pengujian integrasi PostgreSQL");
  assert.notEqual(process.env.NODE_ENV, "production", "Pengujian tidak boleh dijalankan dalam mode produksi");

  const schema = `sbu_case_test_${randomUUID().replaceAll("-", "")}`;
  const admin = new Pool({ connectionString: process.env.DATABASE_URL, max: 1 });
  const temporaryDir = await mkdtemp(join(testDir, ".sbu-case-pg-"));
  let created = false;
  let restricted;
  let server;

  try {
    await admin.query(`CREATE SCHEMA "${schema}"`);
    created = true;
    for (const table of ["sbu_profiles", "sbu_cases"]) {
      await admin.query(`CREATE TABLE "${schema}".${table} (LIKE public.${table} INCLUDING ALL)`);
    }
    // LIKE copies the public serial default; never advance the application's sequence.
    await admin.query(`ALTER TABLE "${schema}".sbu_cases ALTER COLUMN id DROP DEFAULT`);
    await admin.query(`ALTER TABLE "${schema}".sbu_cases ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY`);

    restricted = await createRestrictedRoutePool(admin, schema);
    const isolated = restricted.pool;

    const { rows: [target] } = await isolated.query(`
      SELECT current_schema() AS current_schema,
             (SELECT n.nspname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
              WHERE c.oid = to_regclass('sbu_profiles')) AS profiles_schema,
             (SELECT n.nspname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
              WHERE c.oid = to_regclass('sbu_cases')) AS cases_schema
    `);
    assert.deepEqual(target, {
      current_schema: schema, profiles_schema: schema, cases_schema: schema,
    }, "Route harus memakai tabel salinan, bukan tabel aplikasi");

    const ownerId = `test-owner-${randomUUID()}`;
    await isolated.query("INSERT INTO sbu_profiles (user_id) VALUES ($1)", [ownerId]);
    const { rows: [original] } = await isolated.query(
      `INSERT INTO sbu_cases
       (owner_id, company_name, request_type, qualification, classification, status,
        existing_sbu_expires_on, created_at, updated_at)
       VALUES ($1, 'Perusahaan Awal', 'perpanjangan', 'menengah', 'instalasi mekanikal',
               'ditinjau', '2027-04-15', '2026-02-01T00:00:00Z', '2026-02-02T00:00:00Z')
       RETURNING *`,
      [ownerId],
    );
    const publicCount = async () => (await admin.query(
      "SELECT count(*)::int AS count FROM public.sbu_cases WHERE owner_id = $1", [ownerId],
    )).rows[0].count;
    assert.equal(await publicCount(), 0, "Kasus uji tidak boleh ada di tabel aplikasi");

    // Keep the real route, Drizzle update, and table definitions; replace only auth
    // and the database connection so all writes remain in the disposable schema.
    globalThis.__caseTestDb = drizzle(isolated);
    const { default: router } = await buildCaseRouteFixture(temporaryDir, "__caseTestDb");
    const app = express();
    app.use(express.json());
    app.use("/api", router);
    server = app.listen(0);

    const path = `/api/cases/${original.id}`;
    const updated = await request(server, ownerId, path, {
      method: "PATCH",
      headers: { "content-type": "application/json" },
      body: JSON.stringify({ companyName: "Perusahaan Baru" }),
    });
    assert.equal(updated.status, 200, updated.raw);

    const { rows: [saved] } = await isolated.query("SELECT * FROM sbu_cases WHERE id = $1", [original.id]);
    assert.ok(saved.updated_at > original.updated_at, "Waktu pembaruan harus maju");
    assert.deepEqual(saved, {
      ...original,
      company_name: "Perusahaan Baru",
      updated_at: saved.updated_at,
    }, "Semua kolom yang tidak dikirim harus tetap sama setelah PATCH nyata");
    assert.equal(await publicCount(), 0, "PATCH tidak boleh menyentuh tabel aplikasi");

    const reopened = await request(server, ownerId, path);
    assert.equal(reopened.status, 200, reopened.raw);
    assert.deepEqual(updated.body, reopened.body, "Respons PATCH harus sesuai dengan pembacaan ulang");
    assert.equal(reopened.body.companyName, saved.company_name);
    assert.equal(reopened.body.existingSbuExpiresOn, "2027-04-15T00:00:00.000Z");

    await t.test("ownerId palsu tidak mengubah pemilik atau membuka akses pengguna kedua", async () => {
      const secondOwnerId = `test-other-owner-${randomUUID()}`;
      await isolated.query("INSERT INTO sbu_profiles (user_id) VALUES ($1)", [secondOwnerId]);
      assert.equal(await publicCount(), 0, "Permohonan uji tetap hanya ada di tabel salinan");

      const otherBefore = await request(server, secondOwnerId, path);
      assert.equal(otherBefore.status, 404, otherBefore.raw);

      const forgedPatch = await request(server, ownerId, path, {
        method: "PATCH",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({
          ownerId: secondOwnerId,
          companyName: "Perusahaan Tetap Milik Pertama",
          status: "selesai_persiapan",
        }),
      });
      assert.equal(forgedPatch.status, 200, forgedPatch.raw);
      assert.equal(forgedPatch.body.companyName, "Perusahaan Tetap Milik Pertama");
      assert.equal(forgedPatch.body.status, "selesai_persiapan");
      assert.equal(forgedPatch.body.ownerId, undefined, "Pemilik tidak ada dalam kontrak respons");

      const { rows: [afterForgedPatch] } = await isolated.query(
        "SELECT * FROM sbu_cases WHERE id = $1", [original.id],
      );
      assert.equal(afterForgedPatch.owner_id, ownerId, "Drizzle tidak boleh menyimpan ownerId dari body");
      assert.equal(afterForgedPatch.company_name, forgedPatch.body.companyName);
      assert.equal(afterForgedPatch.status, forgedPatch.body.status);
      assert.equal(await publicCount(), 0, "Perubahan tidak boleh masuk ke tabel aplikasi");

      const firstOwnerDetail = await request(server, ownerId, path);
      assert.equal(firstOwnerDetail.status, 200, firstOwnerDetail.raw);
      assert.deepEqual(firstOwnerDetail.body, forgedPatch.body);

      const secondOwnerDetail = await request(server, secondOwnerId, path);
      assert.equal(secondOwnerDetail.status, 404, secondOwnerDetail.raw);
      assert.deepEqual(secondOwnerDetail.body, { error: "Permohonan tidak ditemukan." });

      const secondOwnerPatch = await request(server, secondOwnerId, path, {
        method: "PATCH",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({ companyName: "Tidak Boleh Diambil Alih" }),
      });
      assert.equal(secondOwnerPatch.status, 404, secondOwnerPatch.raw);
      assert.deepEqual(secondOwnerPatch.body, { error: "Permohonan tidak ditemukan." });
      const { rows: [afterDeniedPatch] } = await isolated.query(
        "SELECT * FROM sbu_cases WHERE id = $1", [original.id],
      );
      assert.deepEqual(afterDeniedPatch, afterForgedPatch, "PATCH pengguna kedua tidak boleh mengubah data");
    });
  } finally {
    try {
      if (server) await new Promise((resolve, reject) => server.close((error) => error ? reject(error) : resolve()));
    } finally {
      delete globalThis.__caseTestDb;
      try {
        // Close route connections and remove their login before dropping its grants' schema.
        if (restricted) await restricted.close();
        if (created) await admin.query(`DROP SCHEMA "${schema}" CASCADE`);
      } finally {
        try {
          await admin.end();
        } finally {
          await rm(temporaryDir, { recursive: true, force: true });
        }
      }
    }
  }
});