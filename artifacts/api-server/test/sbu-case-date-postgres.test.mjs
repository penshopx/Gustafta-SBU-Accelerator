import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { mkdtemp, rm } from "node:fs/promises";
import { createRequire } from "node:module";
import { join } from "node:path";
import { test } from "node:test";
import { fileURLToPath } from "node:url";
import express from "express";
import { build } from "esbuild";
import { drizzle } from "drizzle-orm/node-postgres";
import { createRestrictedRoutePool } from "./helpers/restricted-postgres.mjs";

const testDir = fileURLToPath(new URL(".", import.meta.url));
const { Pool } = createRequire(new URL("../../../lib/db/package.json", import.meta.url))("pg");

test("PATCH tanggal SBU terisi → null → tanggal baru tersimpan dan terbaca lewat GET tanpa mengubah kolom lain", async () => {
  assert.ok(process.env.DATABASE_URL, "DATABASE_URL diperlukan untuk pengujian integrasi PostgreSQL");
  assert.notEqual(process.env.NODE_ENV, "production", "Pengujian tidak boleh dijalankan dalam mode produksi");

  const schema = `sbu_date_test_${randomUUID().replaceAll("-", "")}`;
  const admin = new Pool({ connectionString: process.env.DATABASE_URL, max: 1 });
  const temporaryDir = await mkdtemp(join(testDir, ".sbu-date-pg-"));
  let created = false;
  let restricted;
  let server;

  try {
    await admin.query(`CREATE SCHEMA "${schema}"`);
    created = true;
    for (const table of ["sbu_profiles", "sbu_cases"]) {
      await admin.query(`CREATE TABLE "${schema}".${table} (LIKE public.${table} INCLUDING ALL)`);
    }
    // Copied serial defaults must not advance the application's sequence.
    await admin.query(`ALTER TABLE "${schema}".sbu_cases ALTER COLUMN id DROP DEFAULT`);
    await admin.query(`ALTER TABLE "${schema}".sbu_cases ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY`);
    restricted = await createRestrictedRoutePool(admin, schema);
    const isolated = restricted.pool;

    const { rows: [target] } = await isolated.query(`
      SELECT current_schema() AS current_schema,
             (SELECT n.nspname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
              WHERE c.oid = to_regclass('sbu_profiles')) AS profiles_schema,
             (SELECT n.nspname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
              WHERE c.oid = to_regclass('sbu_cases')) AS cases_schema
    `);
    assert.deepEqual(target, {
      current_schema: schema, profiles_schema: schema, cases_schema: schema,
    }, "Semua pembacaan dan penulisan rute harus memakai tabel salinan");

    const ownerId = `test-date-owner-${randomUUID()}`;
    await isolated.query("INSERT INTO sbu_profiles (user_id) VALUES ($1)", [ownerId]);
    const { rows: [original] } = await isolated.query(`
      INSERT INTO sbu_cases
        (owner_id, company_name, request_type, qualification, classification, status,
         existing_sbu_expires_on, created_at, updated_at)
      VALUES ($1, 'Perusahaan Uji Tanggal', 'perpanjangan', 'menengah', 'instalasi mekanikal',
              'ditinjau', '2027-04-15', '2026-02-01T00:00:00Z', '2026-02-02T00:00:00Z')
      RETURNING *
    `, [ownerId]);
    assert.notEqual(original.existing_sbu_expires_on, null, "Tanggal awal harus terisi");

    // Use the real route, validators, Drizzle and table definitions; only
    // authentication and the connection are replaced for this isolated test.
    globalThis.__caseDateTestDb = drizzle(isolated);
    await build({
      entryPoints: [join(testDir, "../src/routes/sbu.ts")],
      outfile: join(temporaryDir, "route.mjs"),
      bundle: true,
      platform: "node",
      format: "esm",
      external: ["express", "@google-cloud/*"],
      plugins: [{
        name: "isolated-case-date-db",
        setup(builder) {
          builder.onResolve({ filter: /\/workspace-context$/ }, () => ({
            path: join(testDir, "helpers/workspace-context-fixture.mjs"),
          }));
          builder.onResolve({ filter: /^@workspace\/db$/ }, () => ({ path: "db", namespace: "case-date-test" }));
          builder.onResolve({ filter: /^@clerk\/express$/ }, () => ({ path: "auth", namespace: "case-date-test" }));
          builder.onResolve({ filter: /^@workspace\/api-zod$/ }, () => ({
            path: join(testDir, "../../../lib/api-zod/src/index.ts"),
          }));
          builder.onLoad({ filter: /.*/, namespace: "case-date-test" }, (args) => ({
            contents: args.path === "auth"
              ? `export const getAuth = (req) => ({ userId: req.get("x-test-user-id") });`
              : `export * from ${
                JSON.stringify(join(testDir, "../../../lib/db/src/schema/index.ts"))
              }; export const db = globalThis.__caseDateTestDb;`,
            loader: "js",
            resolveDir: testDir,
          }));
        },
      }],
    });
    const { default: router } = await import(join(temporaryDir, "route.mjs"));
    const app = express();
    app.use(express.json());
    app.use("/api", router);
    server = app.listen(0);

    const request = async (options = {}) => {
      const { port } = server.address();
      const response = await fetch(`http://127.0.0.1:${port}/api/cases/${original.id}`, {
        ...options,
        headers: {
          "x-test-user-id": ownerId,
          "X-SBU-Form-Owner": ownerId,
          ...options.headers,
        },
      });
      const raw = await response.text();
      assert.equal(response.status, 200, raw);
      return JSON.parse(raw);
    };
    const before = await request();
    assert.equal(before.existingSbuExpiresOn, "2027-04-15T00:00:00.000Z");

    const patched = await request({
      method: "PATCH",
      headers: { "content-type": "application/json" },
      body: JSON.stringify({ existingSbuExpiresOn: null }),
    });
    assert.equal(patched.existingSbuExpiresOn, null);
    const { rows: [saved] } = await isolated.query("SELECT * FROM sbu_cases WHERE id = $1", [original.id]);
    assert.equal(saved.existing_sbu_expires_on, null, "Kolom DATE PostgreSQL harus benar-benar NULL");
    assert.ok(saved.updated_at > original.updated_at, "Waktu pembaruan harus maju");
    assert.deepEqual(saved, {
      ...original, existing_sbu_expires_on: null, updated_at: saved.updated_at,
    }, "Selain tanggal yang dikosongkan dan updated_at, seluruh kolom harus tetap utuh");
    const { rows: [nullCheck] } = await isolated.query(
      "SELECT existing_sbu_expires_on IS NULL AS date_is_null FROM sbu_cases WHERE id = $1",
      [original.id],
    );
    assert.equal(nullCheck.date_is_null, true);

    const reopened = await request();
    assert.equal(reopened.existingSbuExpiresOn, null, "GET ulang tidak boleh mengembalikan tanggal lama");
    assert.deepEqual(reopened, patched, "GET harus sesuai dengan hasil PATCH");
    assert.deepEqual(reopened, {
      ...before, existingSbuExpiresOn: null, updatedAt: reopened.updatedAt,
    }, "Isian API lainnya tidak boleh berubah");

    const newDate = "2028-02-29";
    const expectedWireDate = `${newDate}T00:00:00.000Z`;
    const restored = await request({
      method: "PATCH",
      headers: { "content-type": "application/json" },
      body: JSON.stringify({ existingSbuExpiresOn: newDate }),
    });
    assert.equal(restored.existingSbuExpiresOn, expectedWireDate,
      "PATCH harus mengembalikan tanggal baru pada tengah malam UTC sesuai kontrak kalender API");
    const { rows: [restoredRow] } = await isolated.query(
      "SELECT * FROM sbu_cases WHERE id = $1", [original.id],
    );
    const { rows: [restoredDate] } = await isolated.query(
      "SELECT existing_sbu_expires_on::text AS calendar_date FROM sbu_cases WHERE id = $1",
      [original.id],
    );
    assert.equal(restoredDate.calendar_date, newDate,
      "Kolom DATE harus menyimpan tanggal kalender baru secara tepat, termasuk hari kabisat");
    assert.ok(restoredRow.updated_at >= saved.updated_at,
      "Waktu pembaruan tidak boleh mundur setelah tanggal diisi kembali");
    assert.deepEqual(restoredRow, {
      ...original,
      existing_sbu_expires_on: restoredRow.existing_sbu_expires_on,
      updated_at: restoredRow.updated_at,
    }, "Pengisian ulang tanggal tidak boleh mengubah kolom database lainnya");

    const reopenedRestored = await request();
    assert.equal(reopenedRestored.existingSbuExpiresOn, expectedWireDate,
      "GET ulang harus mengembalikan tanggal baru, bukan null atau tanggal awal");
    assert.deepEqual(reopenedRestored, restored, "GET harus sesuai dengan PATCH pengisian ulang");
    assert.deepEqual(reopenedRestored, {
      ...before, existingSbuExpiresOn: expectedWireDate, updatedAt: reopenedRestored.updatedAt,
    }, "Pengisian ulang tanggal tidak boleh mengubah isian API lainnya");

    for (const table of ["sbu_profiles", "sbu_cases"]) {
      const column = table === "sbu_profiles" ? "user_id" : "owner_id";
      const { rows: [result] } = await admin.query(
        `SELECT count(*)::int AS count FROM public.${table} WHERE ${column} = $1`, [ownerId],
      );
      assert.equal(result.count, 0, "Data uji tidak boleh masuk ke tabel aplikasi");
    }
  } finally {
    try {
      if (server) await new Promise((resolve, reject) => server.close((error) => error ? reject(error) : resolve()));
    } finally {
      delete globalThis.__caseDateTestDb;
      try {
        if (restricted) await restricted.close();
      } finally {
        try {
          if (created) await admin.query(`DROP SCHEMA "${schema}" CASCADE`);
        } finally {
          await admin.end();
          await rm(temporaryDir, { recursive: true, force: true });
        }
      }
    }
  }
});
