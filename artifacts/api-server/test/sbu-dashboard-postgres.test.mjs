import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { mkdtemp, rm } from "node:fs/promises";
import { createRequire } from "node:module";
import { join } from "node:path";
import { test } from "node:test";
import { fileURLToPath } from "node:url";
import express from "express";
import { build } from "esbuild";
import { drizzle } from "drizzle-orm/node-postgres";
import { createRestrictedRoutePool } from "./helpers/restricted-postgres.mjs";

const testDir = fileURLToPath(new URL(".", import.meta.url));
const { Pool } = createRequire(new URL("../../../lib/db/package.json", import.meta.url))("pg");

async function request(server, userId, path = "/dashboard", { method = "GET", body } = {}) {
  const { port } = server.address();
  const response = await fetch(`http://127.0.0.1:${port}/api${path}`, {
    method,
    headers: {
      "x-test-user-id": userId,
      "X-SBU-Form-Owner": userId,
      ...(body === undefined ? {} : { "Content-Type": "application/json" }),
    },
    ...(body === undefined ? {} : { body: JSON.stringify(body) }),
  });
  const raw = await response.text();
  return { status: response.status, body: raw ? JSON.parse(raw) : null, raw };
}

test("dashboard PostgreSQL menjaga hitungan dan lima terbaru pada data tetap maupun setelah mutasi", async (t) => {
  assert.ok(process.env.DATABASE_URL, "DATABASE_URL diperlukan untuk pengujian integrasi PostgreSQL");
  assert.notEqual(process.env.NODE_ENV, "production", "Pengujian tidak boleh dijalankan dalam mode produksi");

  const schema = `sbu_dashboard_test_${randomUUID().replaceAll("-", "")}`;
  const admin = new Pool({ connectionString: process.env.DATABASE_URL, max: 1 });
  const temporaryDir = await mkdtemp(join(testDir, ".sbu-dashboard-pg-"));
  let created = false;
  let restricted;
  let server;

  try {
    await admin.query(`CREATE SCHEMA "${schema}"`);
    created = true;
    for (const table of ["sbu_profiles", "sbu_cases"]) {
      await admin.query(`CREATE TABLE "${schema}".${table} (LIKE public.${table} INCLUDING ALL)`);
    }
    // A copied serial default must not advance the application's sequence.
    await admin.query(`ALTER TABLE "${schema}".sbu_cases ALTER COLUMN id DROP DEFAULT`);
    await admin.query(`ALTER TABLE "${schema}".sbu_cases ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY`);
    restricted = await createRestrictedRoutePool(admin, schema);
    const isolated = restricted.pool;

    const { rows: [target] } = await isolated.query(`
      SELECT current_schema() AS current_schema,
             (SELECT n.nspname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
              WHERE c.oid = to_regclass('sbu_profiles')) AS profiles_schema,
             (SELECT n.nspname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
              WHERE c.oid = to_regclass('sbu_cases')) AS cases_schema
    `);
    assert.deepEqual(target, {
      current_schema: schema, profiles_schema: schema, cases_schema: schema,
    }, "Koneksi rute harus memilih tabel salinan, bukan tabel aplikasi");
    for (const sql of [
      "EXPLAIN INSERT INTO public.sbu_cases (owner_id, company_name, request_type, qualification, classification) SELECT 'probe', 'probe', 'baru', 'kecil', 'gedung' WHERE false",
      "EXPLAIN UPDATE public.sbu_cases SET status = status WHERE false",
      "EXPLAIN DELETE FROM public.sbu_cases WHERE false",
    ]) {
      await assert.rejects(isolated.query(sql), { code: "42501" },
        "Akun uji tidak boleh menulis permohonan di tabel aplikasi");
    }

    const ownerId = `test-dashboard-owner-${randomUUID()}`;
    const otherOwnerId = `test-dashboard-other-${randomUUID()}`;
    const owners = [ownerId, otherOwnerId];
    await isolated.query("INSERT INTO sbu_profiles (user_id) VALUES ($1), ($2)", owners);
    const tiedAt = "2026-03-10T10:00:00.000Z";
    const newerAt = "2026-03-11T10:00:00.000Z";
    const olderAt = "2026-03-09T10:00:00.000Z";
    // Scramble insertion order. The newer row has the smallest ID and the
    // older row has the largest, so sorting only by ID also fails this test.
    const fixtures = [
      [203, tiedAt, "selesai_persiapan"],
      [206, tiedAt, "draf"],
      [201, tiedAt, "draf"],
      [205, tiedAt, "ditinjau"],
      [202, tiedAt, "ditinjau"],
      [204, tiedAt, "ditinjau"],
      [100, newerAt, "draf"],
      [900, olderAt, "selesai_persiapan"],
    ];
    for (const [id, updatedAt, status] of fixtures) {
      await isolated.query(`
        INSERT INTO sbu_cases
          (id, owner_id, company_name, request_type, qualification, classification, status, created_at, updated_at)
        VALUES ($1, $2, $3, 'baru', 'kecil', 'gedung', $4, '2026-02-01T00:00:00Z', $5)
      `, [id, ownerId, `Perusahaan Uji ${id}`, status, updatedAt]);
    }
    await isolated.query(`
      INSERT INTO sbu_cases
        (id, owner_id, company_name, request_type, qualification, classification, status, updated_at)
      VALUES (999, $1, 'Perusahaan Pengguna Lain', 'baru', 'kecil', 'gedung', 'draf', '2026-03-12T10:00:00Z')
    `, [otherOwnerId]);
    const publicCounts = async () => (await admin.query(`
      SELECT
        (SELECT count(*)::int FROM public.sbu_profiles WHERE user_id = ANY($1::text[])) AS profiles,
        (SELECT count(*)::int FROM public.sbu_cases WHERE owner_id = ANY($1::text[])) AS cases
    `, [owners])).rows[0];
    assert.deepEqual(await publicCounts(), { profiles: 0, cases: 0 },
      "Semua data uji harus berada hanya di tabel salinan");
    const before = (await isolated.query("SELECT * FROM sbu_cases ORDER BY id")).rows;

    // Keep real route, response parsing, Drizzle and PostgreSQL; substitute
    // only session identity and the connection to the disposable tables.
    globalThis.__dashboardTestDb = drizzle(isolated);
    await build({
      entryPoints: [join(testDir, "../src/routes/sbu.ts")],
      outfile: join(temporaryDir, "route.mjs"),
      bundle: true,
      platform: "node",
      format: "esm",
      external: ["express", "@google-cloud/*"],
      plugins: [{
        name: "isolated-dashboard-db",
        setup(builder) {
          builder.onResolve({ filter: /\/workspace-context$/ }, () => ({
            path: join(testDir, "helpers/workspace-context-fixture.mjs"),
          }));
          builder.onResolve({ filter: /^@workspace\/db$/ }, () => ({ path: "db", namespace: "dashboard-test" }));
          builder.onResolve({ filter: /^@clerk\/express$/ }, () => ({ path: "auth", namespace: "dashboard-test" }));
          builder.onResolve({ filter: /^@workspace\/api-zod$/ }, () => ({
            path: join(testDir, "../../../lib/api-zod/src/index.ts"),
          }));
          builder.onLoad({ filter: /.*/, namespace: "dashboard-test" }, (args) => ({
            contents: args.path === "auth"
              ? `export const getAuth = (req) => ({ userId: req.get("x-test-user-id") });`
              : `export { profilesTable, casesTable, evidenceTable, transitionVerificationsTable } from ${
                JSON.stringify(join(testDir, "../../../lib/db/src/schema/sbu.ts"))
              }; export const db = globalThis.__dashboardTestDb;`,
            loader: "js",
            resolveDir: testDir,
          }));
        },
      }],
    });
    const { default: router } = await import(join(temporaryDir, "route.mjs"));
    const app = express();
    app.use(express.json());
    app.use("/api", router);
    server = app.listen(0);

    let firstRecent;
    for (let attempt = 0; attempt < 5; attempt += 1) {
      const { status, body, raw } = await request(server, ownerId);
      assert.equal(status, 200, raw);
      const { recent, ...counts } = body;
      assert.deepEqual(counts, { total: 8, draft: 3, reviewing: 3, prepared: 2 },
        "Hitungan harus meliputi delapan permohonan pemilik, termasuk tiga di luar lima terbaru");
      assert.deepEqual(recent.map((item) => item.id), [100, 206, 205, 204, 203],
        "Waktu terbaru harus mendahului waktu seri; ID menurun menentukan batas lima teratas");
      assert.deepEqual(recent.map((item) => item.updatedAt), [newerAt, tiedAt, tiedAt, tiedAt, tiedAt]);
      assert.ok(!raw.includes("Perusahaan Pengguna Lain"),
        "Permohonan pengguna lain yang lebih baru tidak boleh masuk dashboard");
      if (firstRecent) {
        assert.deepEqual(recent, firstRecent, "Urutan dan anggota lima teratas harus stabil saat GET diulang");
      } else {
        firstRecent = recent;
      }
    }
    assert.deepEqual((await isolated.query("SELECT * FROM sbu_cases ORDER BY id")).rows, before,
      "GET berulang tidak boleh mengubah permohonan salinan");
    assert.deepEqual(await publicCounts(), { profiles: 0, cases: 0 },
      "Permintaan dashboard tidak boleh memasukkan data uji ke tabel aplikasi");

    await t.test("PATCH dan DELETE di dalam/luar lima teratas langsung tercermin tanpa mengubah pengguna lain", async () => {
      const otherDashboard = await request(server, otherOwnerId);
      assert.equal(otherDashboard.status, 200, otherDashboard.raw);
      assert.deepEqual(otherDashboard.body, {
        total: 1, draft: 1, reviewing: 0, prepared: 0,
        recent: otherDashboard.body.recent,
      });
      assert.deepEqual(otherDashboard.body.recent.map((item) => item.id), [999]);
      const otherRows = (await isolated.query(
        "SELECT * FROM sbu_cases WHERE owner_id = $1 ORDER BY id", [otherOwnerId],
      )).rows;

      const assertDashboard = async (expectedCounts, expectedIds) => {
        // Read PostgreSQL independently of the route, after each HTTP mutation.
        const stored = (await isolated.query(
          "SELECT * FROM sbu_cases WHERE owner_id = $1 ORDER BY updated_at DESC, id DESC", [ownerId],
        )).rows;
        const storedCounts = {
          total: stored.length,
          draft: stored.filter((item) => item.status === "draf").length,
          reviewing: stored.filter((item) => item.status === "ditinjau").length,
          prepared: stored.filter((item) => item.status === "selesai_persiapan").length,
        };
        assert.deepEqual(storedCounts, expectedCounts, "Mutasi harus benar-benar tersimpan di PostgreSQL");
        assert.deepEqual(stored.slice(0, 5).map((item) => item.id), expectedIds);
        const dashboard = await request(server, ownerId);
        assert.equal(dashboard.status, 200, dashboard.raw);
        const { recent, ...counts } = dashboard.body;
        assert.deepEqual(counts, storedCounts, "Ringkasan harus langsung mengikuti hitungan tersimpan");
        assert.deepEqual(recent.map((item) => ({
          id: item.id, companyName: item.companyName, status: item.status, updatedAt: item.updatedAt,
        })), stored.slice(0, 5).map((item) => ({
          id: item.id, companyName: item.company_name, status: item.status,
          updatedAt: item.updated_at.toISOString(),
        })), "Anggota, urutan, status, dan waktu terbaru harus sesuai data tersimpan");
        const otherAfter = await request(server, otherOwnerId);
        assert.equal(otherAfter.status, 200, otherAfter.raw);
        assert.deepEqual(otherAfter.body, otherDashboard.body, "Dashboard pengguna lain tidak boleh berubah");
        assert.deepEqual((await isolated.query(
          "SELECT * FROM sbu_cases WHERE owner_id = $1 ORDER BY id", [otherOwnerId],
        )).rows, otherRows, "Data pengguna lain juga harus tetap utuh");
        assert.deepEqual(await publicCounts(), { profiles: 0, cases: 0 },
          "Mutasi rute harus tetap terbatas pada tabel salinan");
        return recent;
      };

      await assertDashboard({ total: 8, draft: 3, reviewing: 3, prepared: 2 }, [100, 206, 205, 204, 203]);
      const patchStatus = async (id, status) => {
        const previous = (await isolated.query(
          "SELECT updated_at FROM sbu_cases WHERE id = $1 AND owner_id = $2", [id, ownerId],
        )).rows[0];
        const patched = await request(server, ownerId, `/cases/${id}`, { method: "PATCH", body: { status } });
        assert.equal(patched.status, 200, patched.raw);
        assert.equal(patched.body.id, id);
        assert.equal(patched.body.status, status);
        assert.ok(new Date(patched.body.updatedAt) > previous.updated_at,
          "PATCH harus memperbarui waktu permohonan");
      };
      const deleteCase = async (id) => {
        const deleted = await request(server, ownerId, `/cases/${id}`, { method: "DELETE" });
        assert.equal(deleted.status, 204, deleted.raw);
        assert.equal(deleted.raw, "");
        assert.deepEqual((await isolated.query("SELECT id FROM sbu_cases WHERE id = $1", [id])).rows, [],
          "DELETE harus benar-benar menghapus baris salinan");
      };

      // Change a current top-five item, then promote an item previously outside it.
      await patchStatus(100, "ditinjau");
      await assertDashboard({ total: 8, draft: 2, reviewing: 4, prepared: 2 }, [100, 206, 205, 204, 203]);
      await patchStatus(202, "selesai_persiapan");
      const beforeDelete = await assertDashboard(
        { total: 8, draft: 2, reviewing: 3, prepared: 3 }, [202, 100, 206, 205, 204],
      );

      // Removing an older item changes counts, but not the five latest members.
      await deleteCase(900);
      const afterOutsideDelete = await assertDashboard(
        { total: 7, draft: 2, reviewing: 3, prepared: 2 }, [202, 100, 206, 205, 204],
      );
      assert.deepEqual(afterOutsideDelete, beforeDelete);

      // Removing a top-five item must backfill with the next stored item.
      await deleteCase(205);
      await assertDashboard({ total: 6, draft: 2, reviewing: 2, prepared: 2 }, [202, 100, 206, 204, 203]);
    });
  } finally {
    try {
      if (server) await new Promise((resolve, reject) => server.close((error) => error ? reject(error) : resolve()));
    } finally {
      delete globalThis.__dashboardTestDb;
      try {
        try {
          if (restricted) await restricted.close();
        } finally {
          if (created) await admin.query(`DROP SCHEMA "${schema}" CASCADE`);
        }
      } finally {
        await admin.end();
        await rm(temporaryDir, { recursive: true, force: true });
      }
    }
  }
});