import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { mkdtemp, rm } from "node:fs/promises";
import { createRequire } from "node:module";
import { join } from "node:path";
import { test } from "node:test";
import { fileURLToPath } from "node:url";
import express from "express";
import { drizzle } from "drizzle-orm/node-postgres";
import { createRestrictedRoutePool } from "./helpers/restricted-postgres.mjs";
import { buildCaseRouteFixture, caseRoutePreflight } from "./helpers/sbu-case-route-fixture.mjs";

const testDir = fileURLToPath(new URL(".", import.meta.url));
const { Pool } = createRequire(new URL("../../../lib/db/package.json", import.meta.url))("pg");
const preflight = caseRoutePreflight("__caseCreateDateTestDb");

test("fixture pembuatan permohonan memuat rute nyata tanpa PostgreSQL", preflight);

test("POST tanggal SBU menolak kalender tidak sah tanpa insert dan menerima hari kabisat", async (t) => {
  await preflight();
  assert.ok(process.env.DATABASE_URL, "DATABASE_URL diperlukan untuk pengujian integrasi PostgreSQL");
  assert.notEqual(process.env.NODE_ENV, "production", "Pengujian tidak boleh dijalankan dalam mode produksi");

  const schema = `sbu_create_date_test_${randomUUID().replaceAll("-", "")}`;
  const admin = new Pool({ connectionString: process.env.DATABASE_URL, max: 1 });
  const temporaryDir = await mkdtemp(join(testDir, ".sbu-create-date-pg-"));
  let created = false;
  let restricted;
  let server;

  try {
    await admin.query(`CREATE SCHEMA "${schema}"`);
    created = true;
    for (const table of ["sbu_profiles", "sbu_cases"]) {
      await admin.query(`CREATE TABLE "${schema}".${table} (LIKE public.${table} INCLUDING ALL)`);
    }
    // Never advance the application sequence through a copied serial default.
    await admin.query(`ALTER TABLE "${schema}".sbu_cases ALTER COLUMN id DROP DEFAULT`);
    await admin.query(`ALTER TABLE "${schema}".sbu_cases ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY`);
    restricted = await createRestrictedRoutePool(admin, schema);
    const isolated = restricted.pool;

    const { rows: [target] } = await isolated.query(`
      SELECT current_schema() AS current_schema,
             (SELECT n.nspname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
              WHERE c.oid = to_regclass('sbu_profiles')) AS profiles_schema,
             (SELECT n.nspname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
              WHERE c.oid = to_regclass('sbu_cases')) AS cases_schema
    `);
    assert.deepEqual(target, {
      current_schema: schema, profiles_schema: schema, cases_schema: schema,
    }, "Rute hanya boleh membaca dan menulis tabel salinan");

    const ownerId = `test-create-date-owner-${randomUUID()}`;
    await isolated.query("INSERT INTO sbu_profiles (user_id, role) VALUES ($1, 'kontraktor')", [ownerId]);
    // Keep one existing row so rejected requests must preserve existing data too.
    await isolated.query(`
      INSERT INTO sbu_cases (owner_id, company_name, request_type, qualification, classification)
      VALUES ($1, 'Perusahaan sebelum pengujian', 'baru', 'kecil', 'bangunan gedung')
    `, [ownerId]);
    const { rows: before } = await isolated.query("SELECT * FROM sbu_cases ORDER BY id");

    // Real route, generated validators, Drizzle and schemas; only authentication,
    // workspace context/audit and the database connection use the shared fixture.
    globalThis.__caseCreateDateTestDb = drizzle(isolated);
    const { default: router } = await buildCaseRouteFixture(temporaryDir, "__caseCreateDateTestDb");
    const app = express();
    app.use(express.json());
    app.use("/api", router);
    server = app.listen(0);
    const request = async (path, body, expectedStatus) => {
      const { port } = server.address();
      const response = await fetch(`http://127.0.0.1:${port}/api${path}`, {
        method: body === undefined ? "GET" : "POST",
        headers: {
          "x-test-user-id": ownerId,
          "X-SBU-Form-Owner": ownerId,
          "content-type": "application/json",
        },
        ...(body === undefined ? {} : { body: JSON.stringify(body) }),
      });
      const raw = await response.text();
      assert.equal(response.status, expectedStatus, raw);
      return JSON.parse(raw);
    };
    const payload = {
      companyName: "Perusahaan Uji Tanggal",
      requestType: "perpanjangan",
      qualification: "menengah",
      classification: "instalasi mekanikal",
    };

    for (const invalidDate of ["2027-02-29", "2028-02-30"]) {
      await t.test(`POST ${invalidDate} menghasilkan 400 tanpa baris baru`, async () => {
        const rejected = await request("/cases", {
          ...payload, existingSbuExpiresOn: invalidDate,
        }, 400);
        assert.equal(rejected.error, "Data permohonan tidak valid.");
        const { rows: after } = await isolated.query("SELECT * FROM sbu_cases ORDER BY id");
        assert.deepEqual(after, before,
          "Penolakan tidak boleh menambah baris atau mengubah permohonan sebelumnya");
        const { rows: [sequence] } = await isolated.query(
          `SELECT last_value, is_called FROM "${schema}".sbu_cases_id_seq`,
        );
        assert.equal(Number(sequence.last_value), before[0].id,
          "Penolakan harus terjadi sebelum insert memakai nomor urut");
        assert.equal(sequence.is_called, true);
      });
    }

    const leapDate = "2028-02-29";
    const accepted = await request("/cases", {
      ...payload, existingSbuExpiresOn: leapDate,
    }, 201);
    assert.equal(accepted.existingSbuExpiresOn, leapDate,
      "Respons POST harus mempertahankan tanggal kalender sah tanpa normalisasi");
    const { rows: saved } = await isolated.query(`
      SELECT id, owner_id, company_name, existing_sbu_expires_on::text AS calendar_date
      FROM sbu_cases WHERE id <> $1 ORDER BY id
    `, [before[0].id]);
    assert.deepEqual(saved, [{
      id: accepted.id,
      owner_id: ownerId,
      company_name: payload.companyName,
      calendar_date: leapDate,
    }], "Hanya satu permohonan baru boleh tersimpan dengan hari kabisat yang tepat");
    const reopened = await request(`/cases/${accepted.id}`, undefined, 200);
    assert.deepEqual(reopened, accepted, "GET ulang harus sesuai dengan hasil pembuatan");

    for (const table of ["sbu_profiles", "sbu_cases"]) {
      const column = table === "sbu_profiles" ? "user_id" : "owner_id";
      const { rows: [result] } = await admin.query(
        `SELECT count(*)::int AS count FROM public.${table} WHERE ${column} = $1`, [ownerId],
      );
      assert.equal(result.count, 0, "Tidak boleh ada data uji di tabel aplikasi");
    }
  } finally {
    try {
      if (server) await new Promise((resolve, reject) => server.close((error) => error ? reject(error) : resolve()));
    } finally {
      delete globalThis.__caseCreateDateTestDb;
      try {
        if (restricted) await restricted.close();
      } finally {
        try {
          if (created) await admin.query(`DROP SCHEMA "${schema}" CASCADE`);
        } finally {
          await admin.end();
          await rm(temporaryDir, { recursive: true, force: true });
        }
      }
    }
  }
});
