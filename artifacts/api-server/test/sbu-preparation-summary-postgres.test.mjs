import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { mkdtemp, rm } from "node:fs/promises";
import { createRequire } from "node:module";
import { join } from "node:path";
import { test } from "node:test";
import { fileURLToPath } from "node:url";
import express from "express";
import { build } from "esbuild";
import { drizzle } from "drizzle-orm/node-postgres";
import { createRestrictedRoutePool } from "./helpers/restricted-postgres.mjs";

const testDir = fileURLToPath(new URL(".", import.meta.url));
const { Pool } = createRequire(new URL("../../../lib/db/package.json", import.meta.url))("pg");
const tables = ["sbu_profiles", "sbu_cases", "sbu_evidence", "sbu_transition_verifications"];

test("GET preparation-summary uses one PostgreSQL snapshot during concurrent updates and revocations", {
  timeout: 60_000,
}, async (t) => {
  assert.ok(process.env.DATABASE_URL, "DATABASE_URL diperlukan untuk uji PostgreSQL");
  assert.notEqual(process.env.NODE_ENV, "production");
  const schema = `sbu_summary_test_${randomUUID().replaceAll("-", "")}`;
  const admin = new Pool({ connectionString: process.env.DATABASE_URL, max: 1 });
  const temporaryDir = await mkdtemp(join(testDir, ".sbu-summary-pg-"));
  const owner = `summary-test-${randomUUID()}`;
  const otherOwner = `summary-other-${randomUUID()}`;
  const track = "transisi_konversi";
  let created = false;
  let restricted, reader, writer, server;
  let afterRead;
  let reads = [];

  try {
    await admin.query(`CREATE SCHEMA "${schema}"`);
    created = true;
    for (const table of tables) {
      await admin.query(`CREATE TABLE "${schema}".${table} (LIKE public.${table} INCLUDING ALL)`);
    }
    for (const table of ["sbu_cases", "sbu_evidence"]) {
      await admin.query(`ALTER TABLE "${schema}".${table} ALTER COLUMN id DROP DEFAULT`);
      await admin.query(`ALTER TABLE "${schema}".${table} ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY`);
    }
    restricted = await createRestrictedRoutePool(admin, schema);
    reader = await restricted.pool.connect();
    writer = await restricted.pool.connect();
    const readerPid = (await reader.query("SELECT pg_backend_pid() AS pid")).rows[0].pid;
    const writerPid = (await writer.query("SELECT pg_backend_pid() AS pid")).rows[0].pid;
    assert.notEqual(readerPid, writerPid, "Pembaca dan penulis harus menggunakan koneksi fisik berbeda");
    for (const client of [reader, writer]) {
      for (const table of tables) {
        const { rows: [target] } = await client.query(`
          SELECT n.nspname AS schema FROM pg_class c
          JOIN pg_namespace n ON n.oid = c.relnamespace WHERE c.oid = to_regclass($1)
        `, [table]);
        assert.equal(target.schema, schema, `Resolusi ${table} harus menuju salinan`);
      }
    }
    await writer.query("INSERT INTO sbu_profiles (user_id) VALUES ($1), ($2)", [owner, otherOwner]);
    const { rows: [item] } = await writer.query(`
      INSERT INTO sbu_cases
        (owner_id, company_name, request_type, qualification, classification)
      VALUES ($1, 'Perusahaan Sebelum', 'perpanjangan', 'kecil', 'gedung') RETURNING id
    `, [owner]);
    await writer.query(`
      INSERT INTO sbu_transition_verifications
        (track, publisher, source_url, document_number, signatory, issued_on, scope,
         document_status, source_verified, expert_name, expert_organization, expert_review,
         expert_reviewed_on, expert_approved, verified_by)
      VALUES ($1, 'Penerbit Uji', 'https://pu.go.id/surat-uji', 'Surat Sebelum',
              'Penandatangan', '2026-04-10', 'Konversi SBU', 'berlaku', true,
              'Ahli Uji', 'LSBU Uji', 'Disetujui sesuai cakupan', '2026-04-11', true, $2)
    `, [track, owner]);

    // Observe real SQL results, then deterministically commit on the second
    // connection before allowing the handler to perform its next SELECT.
    // No database responses or transaction settings are substituted.
    const query = reader.query.bind(reader);
    reader.query = async (...args) => {
      const result = await query(...args);
      const sql = typeof args[0] === "string" ? args[0] : args[0].text;
      const table = /^\s*select\b/i.test(sql)
        ? /from "(sbu_cases|sbu_evidence|sbu_transition_verifications)"/i.exec(sql)?.[1]
        : undefined;
      if (table) {
        reads.push(table);
        if (afterRead) await afterRead(table);
      }
      return result;
    };
    globalThis.__summaryPostgresDb = drizzle(reader);
    await build({
      entryPoints: [join(testDir, "../src/routes/sbu.ts")],
      outfile: join(temporaryDir, "route.mjs"),
      bundle: true, platform: "node", format: "esm",
      external: ["express", "@google-cloud/*"],
      plugins: [{
        name: "summary-postgres-fixture",
        setup(builder) {
          builder.onResolve({ filter: /\/workspace-context$/ }, () => ({
            path: join(testDir, "helpers/workspace-context-fixture.mjs"),
          }));
          builder.onResolve({ filter: /^@workspace\/db$/ }, () => ({ path: "db", namespace: "summary-pg" }));
          builder.onResolve({ filter: /^@clerk\/express$/ }, () => ({ path: "auth", namespace: "summary-pg" }));
          builder.onResolve({ filter: /^@workspace\/api-zod$/ }, () => ({
            path: join(testDir, "../../../lib/api-zod/src/index.ts"),
          }));
          builder.onLoad({ filter: /.*/, namespace: "summary-pg" }, (args) => ({
            contents: args.path === "auth"
              ? `export const getAuth = req => ({ userId: req.get("x-test-user-id") });`
              : `export * from ${JSON.stringify(join(testDir, "../../../lib/db/src/schema/index.ts"))};
                 export const db = globalThis.__summaryPostgresDb;`,
            loader: "js", resolveDir: testDir,
          }));
        },
      }],
    });
    const { default: router } = await import(join(temporaryDir, "route.mjs"));
    const app = express();
    app.use("/api", router);
    server = app.listen(0);
    const request = async (userId = owner) => {
      const response = await fetch(
        `http://127.0.0.1:${server.address().port}/api/cases/${item.id}/preparation-summary`,
        { headers: { "x-test-user-id": userId, "X-SBU-Form-Owner": userId },
          signal: AbortSignal.timeout(10_000) },
      );
      return { response, html: await response.text() };
    };
    const content = html => html
      .replace(/Dibuat: [^<]+ \(UTC\)\./, "Dibuat: (UTC).")
      .replace(/Snapshot [^<]+ \(UTC\)/, "Snapshot (UTC)");
    const assertBefore = html => {
      assert.match(html, /Perusahaan Sebelum/);
      assert.match(html, /legalitas — 1 catatan deklarasi/);
      assert.match(html, /Surat Sebelum/);
      assert.match(html, /Tanggal transisi dari sumber terverifikasi: 2026-10-10/);
      assert.doesNotMatch(html, /Perusahaan Sesudah|Surat Sesudah|tenaga — 1 catatan deklarasi/);
    };
    const assertAfter = (html, revoked) => {
      assert.match(html, /Perusahaan Sesudah/);
      assert.match(html, /tenaga — 1 catatan deklarasi/);
      assert.doesNotMatch(html, /Perusahaan Sebelum|Surat Sebelum|legalitas — 1 catatan deklarasi/);
      if (revoked) {
        assert.doesNotMatch(content(html), /Surat Sesudah|Tanggal transisi dari sumber terverifikasi|2026-10-10|2026-11-12/);
      } else {
        assert.match(html, /Surat Sesudah/);
        assert.match(html, /Tanggal transisi dari sumber terverifikasi: 2026-11-12/);
        assert.doesNotMatch(content(html), /2026-10-10/);
      }
    };

    for (const boundary of ["sbu_cases", "sbu_evidence"]) {
      for (const revoked of [false, true]) {
        await t.test(`commit after ${boundary}; ${revoked ? "revoke" : "update"} verification`, async () => {
          await writer.query("UPDATE sbu_cases SET company_name = 'Perusahaan Sebelum', updated_at = '2026-02-01T00:00:00Z' WHERE id = $1", [item.id]);
          await writer.query("DELETE FROM sbu_evidence WHERE case_id = $1", [item.id]);
          await writer.query("INSERT INTO sbu_evidence (case_id, code, title) VALUES ($1, 'legalitas', 'Judul privat')", [item.id]);
          await writer.query(`
            UPDATE sbu_transition_verifications SET document_number = 'Surat Sebelum',
              issued_on = '2026-04-10', document_status = 'berlaku' WHERE track = $1
          `, [track]);
          const baseline = await request();
          assert.equal(baseline.response.status, 200, baseline.html);
          assertBefore(baseline.html);
          reads = [];
          let committed = false;
          afterRead = async table => {
            if (table !== boundary || committed) return;
            committed = true;
            await writer.query("BEGIN");
            try {
              await writer.query("UPDATE sbu_cases SET company_name = 'Perusahaan Sesudah', updated_at = '2026-02-02T00:00:00Z' WHERE id = $1", [item.id]);
              await writer.query("UPDATE sbu_evidence SET code = 'tenaga', updated_at = now() WHERE case_id = $1", [item.id]);
              await writer.query(`
                UPDATE sbu_transition_verifications SET document_number = 'Surat Sesudah',
                  issued_on = '2026-05-12', document_status = $1, updated_at = now() WHERE track = $2
              `, [revoked ? "dicabut" : "berlaku", track]);
              await writer.query("COMMIT");
            } catch (error) {
              await writer.query("ROLLBACK");
              throw error;
            }
          };
          const snapshot = await request();
          afterRead = undefined;
          assert.equal(snapshot.response.status, 200, snapshot.html);
          assert.equal(snapshot.response.headers.get("cache-control"), "private, no-store");
          assert.equal(committed, true, "Pembaruan harus selesai di antara pembacaan handler");
          assert.deepEqual(reads, ["sbu_cases", "sbu_evidence", "sbu_transition_verifications"]);
          assertBefore(snapshot.html);
          assert.equal(content(snapshot.html), content(baseline.html),
            "Seluruh ringkasan, termasuk waktu pembaruan kasus, harus sesuai snapshot sebelum commit");
          const latest = await request();
          assert.equal(latest.response.status, 200, latest.html);
          assertAfter(latest.html, revoked);
        });
      }
    }
    await t.test("another account is rejected before evidence or verification reads", async () => {
      reads = [];
      const denied = await request(otherOwner);
      assert.equal(denied.response.status, 404, denied.html);
      assert.deepEqual(reads, ["sbu_cases"], "Kasus asing harus ditolak sebelum membaca bukti dan verifikasi");
      assert.doesNotMatch(denied.html, /Perusahaan|Judul privat|Surat/);
    });
    // Safety checks use SELECT only against live tables.
    for (const [table, column] of [
      ["sbu_profiles", "user_id"], ["sbu_cases", "owner_id"],
      ["sbu_transition_verifications", "verified_by"],
    ]) {
      const { rows: [live] } = await admin.query(
        `SELECT count(*)::int AS count FROM public.${table} WHERE ${column} IN ($1, $2)`,
        [owner, otherOwner],
      );
      assert.equal(live.count, 0, "Fixture tidak boleh masuk ke data aplikasi");
    }
  } finally {
    afterRead = undefined;
    try {
      if (server) await new Promise((resolve, reject) => server.close(error => error ? reject(error) : resolve()));
    } finally {
      delete globalThis.__summaryPostgresDb;
      reader?.release();
      writer?.release();
      try {
        if (restricted) await restricted.close();
      } finally {
        try {
          if (created) await admin.query(`DROP SCHEMA "${schema}" CASCADE`);
        } finally {
          await admin.end();
          await rm(temporaryDir, { recursive: true, force: true });
        }
      }
    }
  }
});
